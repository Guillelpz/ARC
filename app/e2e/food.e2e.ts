import { expect, test, type Page } from '@playwright/test'

const nav = (page: Page, name: string) => page.getByRole('navigation', { name: 'Principal' }).getByRole('button', { name }).click()
const noOverflow = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)

test('E-FD1 a 320 px: objetivo, añadido rápido y alimento del catálogo; la fila «Hoy» y la recarga', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.goto('./')
  await nav(page, 'Yo')
  await page.getByRole('button', { name: /^Comida/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Comida' })).toBeVisible()
  expect(await noOverflow(page)).toBe(true)

  await page.getByLabel(/^Calorías al día/).fill('2000')
  await page.getByRole('button', { name: 'Guardar objetivo' }).click()
  await expect(page.getByText('Cuenta en Dieta entre 1.800 y 2.200 kcal (90–110 %).')).toBeVisible()

  await page.getByRole('button', { name: 'Añadido rápido' }).click()
  await page.getByLabel(/^Calorías \(kcal\)/).fill('1000')
  await page.locator('#food-quick').getByRole('button', { name: 'Añadir' }).click()
  await expect(page.getByText('Añadido: Añadido rápido (1.000 kcal)')).toBeVisible()

  await page.getByLabel('Buscar alimento').fill('arroz')
  await page.getByRole('button', { name: /^Arroz blanco cocido/ }).click()
  await page.getByLabel('Cantidad').fill('700')
  await expect(page.getByText(/^910 kcal · /)).toBeVisible()
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  await expect(page.getByText('Añadido: Arroz blanco cocido 700 g (910 kcal) · Día dentro del objetivo: +1 Dieta')).toBeVisible()
  await expect(page.getByText('Dentro del objetivo: cuenta en Dieta')).toBeVisible()
  expect(await noOverflow(page)).toBe(true)

  await nav(page, 'Inicio')
  await expect(page.getByRole('button', { name: /^Comida.*1\.910 \/ 2\.000 kcal$/ })).toBeVisible()
  expect(await noOverflow(page)).toBe(true)

  await page.reload()
  await nav(page, 'Yo')
  await page.getByRole('button', { name: /^Comida/ }).click()
  const diary = page.getByRole('region', { name: 'Diario' })
  await expect(diary.getByText('910 kcal')).toBeVisible()
  await expect(diary.getByText('1.000 kcal')).toBeVisible()
  expect(await noOverflow(page)).toBe(true)
  await nav(page, 'HERO')
  await expect(page.getByRole('group', { name: 'Dieta' })).toBeVisible()
})

test('E-FD2 a 320 px: alimento propio, plato de un toque, resumen semanal y recarga', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.goto('./')
  await nav(page, 'Yo')
  await page.getByRole('button', { name: /^Comida/ }).click()

  await page.getByRole('button', { name: 'Crear alimento' }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Bizcocho casero')
  await page.getByLabel(/^Calorías \(kcal\)/).fill('400')
  await page.getByLabel(/^Proteína/).last().fill('6')
  await page.getByLabel(/^Carbohidratos/).last().fill('50')
  await page.getByLabel(/^Grasa/).last().fill('20')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByLabel('Cantidad').fill('100')
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  await page.getByLabel('Buscar alimento').fill('huevo')
  await page.getByRole('button', { name: /^Huevo/ }).first().click()
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  expect(await noOverflow(page)).toBe(true)

  await page.getByRole('button', { name: 'Guardar como plato' }).click()
  const checks = page.getByRole('group', { name: 'Alimentos del día' }).getByRole('checkbox')
  await checks.nth(0).check()
  await checks.nth(1).check()
  await page.getByLabel('Nombre del plato').fill('Merienda')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByText('Plato guardado: Merienda')).toBeVisible()
  await page.getByRole('button', { name: 'Añadir plato Merienda' }).click()
  await expect(page.getByText(/^Añadido: Merienda \(2 alimentos\)/)).toBeVisible()
  await expect(page.getByRole('region', { name: 'Diario' }).getByRole('button', { name: /^Deshacer/ })).toHaveCount(4)
  await expect(page.getByRole('region', { name: 'Semana' }).getByText(/^2 días|^1 día/)).toBeVisible()
  expect(await noOverflow(page)).toBe(true)

  await page.reload()
  await nav(page, 'Yo')
  await page.getByRole('button', { name: /^Comida/ }).click()
  await expect(page.getByRole('region', { name: 'Platos' }).getByText('Merienda')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Diario' }).getByRole('button', { name: /^Deshacer/ })).toHaveCount(4)
})

test('E-FD3 a 320 px: copiar el día anterior, recargar y deshacer', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.goto('./')
  await nav(page, 'Yo')
  await page.getByRole('button', { name: /^Comida/ }).click()
  await page.getByRole('button', { name: 'Ayer' }).click()
  await page.getByRole('button', { name: 'Añadido rápido' }).click()
  await page.getByLabel(/^Calorías \(kcal\)/).fill('600')
  await page.locator('#food-quick').getByRole('button', { name: 'Añadir' }).click()
  await expect(page.getByText('Añadido: Añadido rápido (600 kcal)')).toBeVisible()
  await page.getByRole('button', { name: 'Hoy', exact: true }).click()
  await page.getByRole('button', { name: 'Copiar día anterior' }).click()
  await expect(page.getByText('Copiado: 1 alimento · 600 kcal')).toBeVisible()
  expect(await noOverflow(page)).toBe(true)

  await page.reload()
  await nav(page, 'Yo')
  await page.getByRole('button', { name: /^Comida/ }).click()
  const diary = page.getByRole('region', { name: 'Diario' })
  await expect(diary.getByText('600 kcal')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Copiar día anterior' })).toBeDisabled()
  await diary.getByRole('button', { name: /^Deshacer Añadido rápido/ }).click()
  await expect(diary.getByText('Nada apuntado este día.')).toBeVisible()
  expect(await noOverflow(page)).toBe(true)
})
